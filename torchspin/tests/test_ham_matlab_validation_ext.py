# Comparison
# ---------------------------------------------------------------------------

def assert_close(torch_mat, matlab_mat, name):
    a = torch_mat.detach().cpu().numpy()
    if hasattr(matlab_mat, 'toarray'):      # scipy sparse (EasySpin sparse output)
        matlab_mat = matlab_mat.toarray()
    b = np.asarray(matlab_mat)
    if b.ndim == 0:
        b = b.reshape(1, 1)
    assert a.shape == b.shape, f"{name}: shape {a.shape} vs MATLAB {b.shape}"
    diff = np.abs(a - b)
    scale = max(np.max(np.abs(b)), 1.0)
    max_diff = float(np.max(diff)) if diff.size else 0.0
    assert max_diff <= ATOL + RTOL * scale, (
        f"{name}: max |diff| = {max_diff:.3e} (scale {scale:.3e})")


def _B0(case):
    return [float(x) for x in _arr(case.B0).ravel()]


# Map from stored matrix field -> callable(sys, case) producing the torchspin
# counterpart.  H0/mux/muy/muz/H are handled generically.
_TERM_BUILDERS = {
    'Hzf':     lambda s, c: ham_zf(s),
    'Hhf':     lambda s, c: ham_hf(s),
    'Hhf_e2n2': lambda s, c: ham_hf(s, [2], [2]),
    'Hee':     lambda s, c: ham_ee(s),
    'Hee_12':  lambda s, c: ham_ee(s, [1, 2]),
    'Hee_13':  lambda s, c: ham_ee(s, [1, 3]),
    'Hee_23':  lambda s, c: ham_ee(s, [2, 3]),
    'Hnq':     lambda s, c: ham_nq(s),
    'Hnq_2':   lambda s, c: ham_nq(s, [2]),
    'Hnn':     lambda s, c: ham_nn(s),
    'Hnn_12':  lambda s, c: ham_nn(s, [1, 2]),
    'Hnn_13':  lambda s, c: ham_nn(s, [1, 3]),
    'Hnn_23':  lambda s, c: ham_nn(s, [2, 3]),
    'Hnz':     lambda s, c: ham_nz(s, _B0(c)),
    'Hnz_1':   lambda s, c: ham_nz(s, _B0(c), [1]),
    'Hnz_2':   lambda s, c: ham_nz(s, _B0(c), [2]),
    'Hez':     lambda s, c: ham_ez(s, _B0(c)),
    'mux_e':   lambda s, c: ham_ez(s)[0],
    'muy_e':   lambda s, c: ham_ez(s)[1],
    'muz_e':   lambda s, c: ham_ez(s)[2],
    'mux_e2':  lambda s, c: ham_ez(s, None, [2])[0],
    'muy_e2':  lambda s, c: ham_ez(s, None, [2])[1],
    'muz_e2':  lambda s, c: ham_ez(s, None, [2])[2],
    'mux_n':   lambda s, c: ham_nz(s)[0],
    'muy_n':   lambda s, c: ham_nz(s)[1],
    'muz_n':   lambda s, c: ham_nz(s)[2],
    'Hezho':   lambda s, c: ham_ezho(s, _B0(c)),
    'G0':      lambda s, c: ham_ezho(s)[0],
    'G1x':     lambda s, c: ham_ezho(s)[1][0],
    'G1y':     lambda s, c: ham_ezho(s)[1][1],
    'G1z':     lambda s, c: ham_ezho(s)[1][2],
    'Hcf':     lambda s, c: ham_cf(s),
    'Hso':     lambda s, c: ham_so(s),
    'Hoz':     lambda s, c: ham_oz(s, _B0(c)),
}

_META_FIELDS = {'name', 'Sys', 'B0', 'note', 'note_ham'}


def _case_names():
    try:
        return sorted(get_cases().keys())
    except Exception:  # pragma: no cover - missing .mat handled in test body
        return []


# Historical note: before 2026-09-01 torchspin ham() omitted the higher-order
# Zeeman terms (never called ham_ezho) and SpinSystem defaulted g to gfree even
# when Ham110/Ham112 replaced the ordinary Zeeman term.  Both fixed.


def _has_ho_zeeman(case):
    return any(f.startswith('Ham') for f in _fields(case.Sys))


def _check_generic(sys, case):
    """ham(sys) -> (H0, mux, muy, muz) and ham(sys, B0) against the reference."""
    fields = _fields(case)
    if 'H0' in fields and np.asarray(case.mux).dtype != object:
        H0, mux, muy, muz = ham(sys)
        assert_close(H0, case.H0, 'H0')
        assert_close(mux, case.mux, 'mux')
        assert_close(muy, case.muy, 'muy')
        assert_close(muz, case.muz, 'muz')
    if 'H' in fields:
        assert_close(ham(sys, _B0(case)), case.H, 'H(B0)')


@pytest.mark.parametrize("case_name", _case_names())
def test_ham_ext(case_name):
    """Individual interaction terms and (for ordinary systems) the full ham()."""
    case = get_cases()[case_name]
    if case_name in XFAIL:
        pytest.xfail(XFAIL[case_name])

    sys = sys_from_matlab(case.Sys)
    fields = _fields(case)

    # Full-Hamiltonian checks for systems with Ham* terms live in
    # test_ham_ext_ho_zeeman_full (known discrepancy).
    if not _has_ho_zeeman(case):
        _check_generic(sys, case)

    for fld in fields:
        if fld in _META_FIELDS or fld in ('H0', 'mux', 'muy', 'muz', 'H'):
            continue
        builder = _TERM_BUILDERS.get(fld)
        assert builder is not None, f"no torchspin builder for field {fld}"
        assert_close(builder(sys, case), getattr(case, fld), fld)


@pytest.mark.parametrize(
    "case_name", [n for n in _case_names() if _has_ho_zeeman(get_cases()[n])])
def test_ham_ext_ho_zeeman_full(case_name):
    """ham()/ham(B0) for systems with Sys.Ham* terms (ham_ezho folded into ham())."""
    case = get_cases()[case_name]
    _check_generic(sys_from_matlab(case.Sys), case)


def test_reference_case_count():
    """Guard: the reference set should keep its full breadth."""
    assert len(get_cases()) >= 80
