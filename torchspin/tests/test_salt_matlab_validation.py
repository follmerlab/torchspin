# ---------------------------------------------------------------------------
# Grid handling: [N_coarse, N_interp] GridSize and projection vs. reference
# ---------------------------------------------------------------------------


def test_salt_gridsize_interp_matches_reference_grid():
    """GridSize=[20, 5] (the reference's Opt.GridSize) reproduces MATLAB to
    cosine >= 0.9999: transitions are interpolated 5x on the orientation grid
    and projected as triangles (EasySpin salt.m), not binned as sticks."""
    ref = _load_data("salt_1H_rhombicg.mat")
    y_ref = np.asarray(ref['y'], dtype=float).ravel()
    sys = SpinSystem(S=[0.5], g=[[2.0, 2.01, 2.02]],
                     Nucs='1H', A=[[-2.0, -2.0, 4.0]])
    x, y = _run_salt_endor(sys, field_mT=326.5, rf_range=(10, 20),
                           n_points=y_ref.size, lw=0.1, mw_freq=9.7,
                           grid_size=[20, 5])
    y_i = _interp_to_ref(x, y, np.asarray(ref['x'], dtype=float).ravel())
    cos = _cosine(y_i, y_ref)
    assert cos > 0.9999, f"salt [20,5] cosine {cos:.5f} < 0.9999"
    coef = float(np.dot(y_i, y_ref) / np.dot(y_i, y_i))
    resid = np.abs(y_ref - coef * y_i) / np.abs(y_ref).max()
    assert resid.max() < 0.01, f"max normalized residual {resid.max():.4f} >= 0.01"


def test_salt_default_options_gridsize_list():
    """Default Options() carries GridSize=[19, 4]; salt must accept it."""
    sys = SpinSystem(S=[0.5], g=[[2.0, 2.01, 2.02]],
                     Nucs='1H', A=[[-2.0, -2.0, 4.0]])
    exp = Experiment(Field=326.5, mwFreq=9.7)
    x, y = salt(sys, exp, Options(), freq_range=(10, 20), n_points=256, lw_mhz=0.1)
    y = np.asarray(y)
    assert y.shape == (256,) and np.all(np.isfinite(y)) and y.max() > 0
