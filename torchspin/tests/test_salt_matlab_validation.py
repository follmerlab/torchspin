"""MATLAB cross-validation for salt (powder ENDOR) against EasySpin references.

References generated by ``tests/data/generate_salt_refs.m`` (EasySpin, MATLAB
R2024b). Each ``.mat`` holds ``data.x`` (RF axis, MHz), ``data.y`` (spectrum),
and the generating ``Sys``/``Exp``/``Opt`` structs.

EasySpin salt semantics targeted here (fixed-field ENDOR):
  - ``Exp.Field``  — static field, mT
  - ``Exp.Range``  — RF frequency window, MHz
  - ``Exp.nPoints``— points across ``Exp.Range`` (default 1024)
  - ``Sys.lwEndor``— Gaussian FWHM (MHz)
  - ``Exp.ExciteWidth`` + ``Exp.mwFreq`` — optional orientation selection
"""

import os

import numpy as np
import pytest

try:
    from scipy.io import loadmat
except ImportError:  # pragma: no cover
    loadmat = None

from torchspin.experiment import Experiment, Options
from torchspin.salt import salt
from torchspin.spinsystem import SpinSystem

DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "data")


def _load_data(filename):
    if loadmat is None:
        pytest.skip("scipy not installed")
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        pytest.skip(f"Reference file not found: {path}")
    return loadmat(path, simplify_cells=True)["data"]


def _cosine(a, b):
    a = np.asarray(a, dtype=float).ravel()
    b = np.asarray(b, dtype=float).ravel()
    n = min(len(a), len(b))
    a, b = a[:n], b[:n]
    return float(abs(np.dot(a, b)) /
                 (np.linalg.norm(a) * np.linalg.norm(b) + 1e-30))


def _run_salt_endor(sys, field_mT, rf_range, n_points, lw, mw_freq,
                    excite_width=None, grid_size=31):
    """Run torchspin salt in fixed-field EasySpin-equivalent mode."""
    exp = Experiment(Field=field_mT, mwFreq=mw_freq)
    if excite_width is not None:
        exp.ExciteWidth = excite_width
    opt = Options()
    opt.GridSize = grid_size
    x, y = salt(sys, exp, opt,
                freq_range=tuple(rf_range), n_points=n_points, lw_mhz=lw)
    return np.asarray(x), np.asarray(y)


def _interp_to_ref(x_py, y_py, x_ref):
    return np.interp(x_ref, x_py, y_py)


# ---------------------------------------------------------------------------
# Case 1: rhombic g + 1H axial A, X-band (salt_invariance_axial1 base)
# ---------------------------------------------------------------------------


def test_salt_1H_rhombicg_cosine():
    """1H powder ENDOR, rhombic g: cosine vs MATLAB >= 0.999."""
    ref = _load_data("salt_1H_rhombicg.mat")
    sys = SpinSystem(S=[0.5], g=[[2.0, 2.01, 2.02]],
                     Nucs='1H', A=[[-2.0, -2.0, 4.0]])
    x, y = _run_salt_endor(sys, field_mT=326.5, rf_range=(10, 20),
                           n_points=len(np.ravel(ref['y'])), lw=0.1,
                           mw_freq=9.7)
    y_ref = np.asarray(ref['y'], dtype=float).ravel()
    x_ref = np.asarray(ref['x'], dtype=float).ravel()
    y_i = _interp_to_ref(x, y, x_ref)
    cos = _cosine(y_i, y_ref)
    assert cos > 0.999, f"salt 1H rhombic-g cosine {cos:.4f} < 0.999"


