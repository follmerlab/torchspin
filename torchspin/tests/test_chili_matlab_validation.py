"""MATLAB validation tests for torchspin.chili.

Reference spectra are generated by tests/generate_chili_refs.m using MATLAB's
EasySpin chili().  Each test loads a .mat file and compares via:
  1. Finiteness — no NaN/Inf in output
  2. Signal-to-noise — peak must be well above numerical noise floor
  3. Cosine similarity — normalized shape match (scale-invariant)
  4. Peak position — dominant peaks must align within tolerance
  5. Normalized amplitude — peak-height ratio after normalization

Run the MATLAB script first:
    matlab -batch "addpath('easyspin'); run('tests/generate_chili_refs.m')"

Then run these tests:
    python -m pytest torchspin/tests/test_chili_matlab_validation.py -v
"""
import math
from pathlib import Path

import numpy as np
import pytest

from torchspin import SpinSystem, chili, ChiliOptions
from torchspin.experiment import Experiment

DATA_DIR = Path(__file__).parent.parent.parent / "tests" / "data"


def _ref(name: str) -> Path:
    return DATA_DIR / name


def _load_mat(path: Path) -> dict:
    from scipy.io import loadmat
    return loadmat(str(path))


# ---------------------------------------------------------------------------
# Validation helpers with numerical noise guardrails
# ---------------------------------------------------------------------------

def _validate_spectrum(spc: np.ndarray, B: np.ndarray, spc_ref: np.ndarray,
                       label: str, cos_threshold: float = 0.90,
                       snr_threshold: float = 10.0,
                       peak_tol_mT: float = 0.5):
    """Multi-metric validation of a chili spectrum against MATLAB reference.

    Checks (in order):
      1. Finiteness: no NaN or Inf
      2. SNR: peak signal / noise floor > snr_threshold
      3. Cosine similarity > cos_threshold
      4. Peak position error < peak_tol_mT
      5. Normalized peak count agreement

    Returns dict of all metrics for diagnostics.
    """
    spc = np.asarray(spc, dtype=float)
    spc_ref = np.asarray(spc_ref, dtype=float)
    B = np.asarray(B, dtype=float)
    metrics = {}

    # 1. Finiteness
    assert np.all(np.isfinite(spc)), f"{label}: Python spectrum contains NaN/Inf"
    assert np.all(np.isfinite(spc_ref)), f"{label}: MATLAB reference contains NaN/Inf"

    # 2. Signal-to-noise ratio
    # Use the bottom 25th percentile of |spectrum| as noise floor estimate
    sorted_abs = np.sort(np.abs(spc))
    noise_floor = np.percentile(sorted_abs, 25)
    peak_signal = np.max(np.abs(spc))
    if noise_floor > 0:
        snr = peak_signal / noise_floor
    else:
        # If noise floor is exactly 0, spectrum is clean
        snr = float('inf')
    metrics['snr'] = snr
    assert snr > snr_threshold, (
        f"{label}: SNR too low ({snr:.1f} < {snr_threshold}). "
        f"Peak signal may be at numerical noise level."
    )

    # 3. Cosine similarity (scale-invariant shape match)
    na = np.linalg.norm(spc)
    nb = np.linalg.norm(spc_ref)
    assert na > 1e-30, f"{label}: Python spectrum is near-zero (norm={na:.2e})"
    assert nb > 1e-30, f"{label}: MATLAB reference is near-zero (norm={nb:.2e})"
    cos = float(np.dot(spc / na, spc_ref / nb))
    metrics['cosine'] = cos
    assert cos > cos_threshold, (
        f"{label}: Cosine similarity too low ({cos:.4f} < {cos_threshold})"
    )

    # 4. Peak position matching
    # Normalize both to [0, 1] for peak detection
    spc_norm = spc / peak_signal
    spc_ref_norm = spc_ref / np.max(np.abs(spc_ref))

    from scipy.signal import find_peaks
    # Find peaks above 10% of max in both spectra
    peaks_py, props_py = find_peaks(spc_norm, height=0.10)
    peaks_ref, props_ref = find_peaks(spc_ref_norm, height=0.10)
    metrics['n_peaks_py'] = len(peaks_py)
    metrics['n_peaks_ref'] = len(peaks_ref)

    if len(peaks_py) > 0 and len(peaks_ref) > 0:
        # Match each reference peak to nearest Python peak
        max_err = 0.0
        for pr in peaks_ref:
            dists = np.abs(B[peaks_py] - B[pr])
            max_err = max(max_err, dists.min())
        metrics['max_peak_error_mT'] = max_err
        assert max_err < peak_tol_mT, (
            f"{label}: Peak position error too large ({max_err:.4f} mT > {peak_tol_mT} mT)"
        )

    # 5. Normalized max-amplitude ratio (after peak-normalizing each)
    amp_ratio = spc_norm.max() / spc_ref_norm.max()  # should be ~1.0
    metrics['amp_ratio'] = amp_ratio

    return metrics


# ---------------------------------------------------------------------------
# Case 1: Anisotropic g, no nucleus, tcorr = 1e-9 s
# Slow-motion broadening — tests basic SLE + Lanczos.
# ---------------------------------------------------------------------------

REF1 = _ref("chili_ref_isog_notcorr.mat")

@pytest.mark.skipif(not REF1.exists(), reason="MATLAB reference not generated")
def test_chili_anisog_nonuc_tcorr1ns():
    """Anisotropic g [2.009,2.006,2.002], no nucleus, tcorr=1ns."""
    data = _load_mat(REF1)
    B_ref = data["B1"].ravel()
    spc_ref = data["spc1"].ravel()
    mwFreq = float(np.asarray(data["mwFreq"]).squeeze())

    sys = SpinSystem(S=[0.5], g=[[2.009, 2.006, 2.002]], tcorr=1e-9, lw=[0.0, 0.0])
    exp = Experiment(
        mwFreq=mwFreq,
        Range=[float(B_ref[0]), float(B_ref[-1])],
        nPoints=len(B_ref),
        Harmonic=0,
    )
    opt = ChiliOptions(LLMK=[14, 7, 2, 6], max_iter=500)
    _, spc = chili(sys, exp, opt)

    B_our = np.linspace(B_ref[0], B_ref[-1], len(spc))
    spc_ref_interp = np.interp(B_our, B_ref, spc_ref)

    metrics = _validate_spectrum(spc, B_our, spc_ref_interp,
                                 label="Case 1 (aniso g, no nuc)",
                                 cos_threshold=0.90)
    print(f"  Case 1 metrics: {metrics}")


