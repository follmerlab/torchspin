def test_chili_self_consistency():
    """chili with same params twice should give identical output (determinism)."""
    sys = SpinSystem(S=[0.5], g=[[2.009, 2.006, 2.002]], tcorr=1e-9, lw=[0.0, 0.0])
    exp = Experiment(mwFreq=9.5, Range=[334, 342], nPoints=256, Harmonic=0)
    opt = ChiliOptions(LLMK=[8, 5, 0, 2], max_iter=200)
    _, spc1 = chili(sys, exp, opt)
    _, spc2 = chili(sys, exp, opt)
    spc1, spc2 = np.asarray(spc1), np.asarray(spc2)
    assert np.all(np.isfinite(spc1)), "Spectrum 1 contains NaN/Inf"
    assert np.allclose(spc1, spc2), "chili is not deterministic"


def test_chili_tcorr_scaling():
    """Longer tcorr -> broader spectrum (slower motion = more broadening)."""
    exp = Experiment(mwFreq=9.5, Range=[334, 342], nPoints=256, Harmonic=0)
    opt = ChiliOptions(LLMK=[10, 7, 0, 2], max_iter=300)

    # A small Gaussian width keeps the fast-motion line resolvable on the grid
    # (without it the near-delta line's sampled peak is meaningless).
    sys_fast = SpinSystem(S=[0.5], g=[[2.008, 2.006, 2.003]], tcorr=1e-10, lw=[0.1, 0.0])
    sys_slow = SpinSystem(S=[0.5], g=[[2.008, 2.006, 2.003]], tcorr=1e-8, lw=[0.1, 0.0])

    _, spc_fast = chili(sys_fast, exp, opt)
    _, spc_slow = chili(sys_slow, exp, opt)
    spc_fast, spc_slow = np.asarray(spc_fast), np.asarray(spc_slow)

    assert np.all(np.isfinite(spc_fast)), "Fast spectrum contains NaN/Inf"
    assert np.all(np.isfinite(spc_slow)), "Slow spectrum contains NaN/Inf"

    # Fast motion: a narrower line. (The slow-motion powder-like pattern can
    # have the higher peak — EasySpin gives 1450 vs 1934 for these inputs — so
    # compare the extent of the spectrum above half maximum instead.)
    def extent(y):
        return int((y > 0.5 * y.max()).sum())
    assert extent(spc_fast) < extent(spc_slow), (extent(spc_fast), extent(spc_slow))


def test_chili_output_positive():
    """Absorption spectrum (Harmonic=0) should be non-negative."""
    sys = SpinSystem(S=[0.5], g=[[2.009, 2.006, 2.002]], tcorr=1e-9, lw=[0.0, 0.0])
    exp = Experiment(mwFreq=9.5, Range=[334, 342], nPoints=256, Harmonic=0)
    opt = ChiliOptions(LLMK=[10, 7, 0, 2], max_iter=300)
    _, spc = chili(sys, exp, opt)
    spc = np.asarray(spc)

    assert np.all(np.isfinite(spc)), "Spectrum contains NaN/Inf"
    # Absorption should be non-negative (small negative from numerics is OK)
    min_val = spc.min()
    assert min_val > -0.01 * spc.max(), (
        f"Significant negative values in absorption spectrum: min={min_val:.3e}, max={spc.max():.3e}"
    )
