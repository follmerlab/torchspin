"""
MATLAB validation tests for torchspin.endorfrq and torchspin.salt.

Reference data is generated by running tests/generate_endorfrq_refs.m in MATLAB
(EasySpin must be on the path).  Tests are skipped if the .mat files are absent.

Orientation convention mapping:
  MATLAB Exp.SampleFrame = [0, beta, 0]
  → field at phi=0, theta=beta in torchspin endorfrq()

Comparison metric for single-orientation ENDOR:
  - Match sorted frequency positions within ±1.0 MHz
  - Match number of significant lines (rel. intensity > 0.01)

Comparison metric for powder (salt):
  - Cosine similarity > 0.97 after interpolation to common grid
"""

import math
from pathlib import Path

import numpy as np
import pytest
import torch

try:
    from scipy.io import loadmat
    from scipy.interpolate import interp1d
    SCIPY_AVAILABLE = True
except ImportError:
    SCIPY_AVAILABLE = False

from torchspin.spinsystem import SpinSystem
from torchspin.experiment import Experiment, Options
from torchspin.endorfrq import endorfrq
from torchspin.salt import salt

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

DATA_DIR = Path(__file__).parent.parent.parent / "tests" / "data"


def _require_mat(filename: str):
    """Skip test if scipy or .mat file unavailable."""
    if not SCIPY_AVAILABLE:
        pytest.skip("scipy not installed")
    path = DATA_DIR / filename
    if not path.exists():
        pytest.skip(
            f"Reference file not found: {path}\n"
            "Run tests/generate_endorfrq_refs.m in MATLAB to generate it."
        )
    return path


def _cosine_similarity(a: np.ndarray, b: np.ndarray) -> float:
    a = a / np.abs(a).max()
    b = b / np.abs(b).max()
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b)))


def _match_lines(
    ref_pos: np.ndarray,
    ref_int: np.ndarray,
    our_pos: np.ndarray,
    our_int: np.ndarray,
    int_threshold: float = 0.01,
    tol_mhz: float = 1.0,
) -> tuple[int, int]:
    """
    Count how many strong MATLAB lines have a torchspin match within tol_mhz.

    Returns
    -------
    n_matched : int
        Number of strong MATLAB lines matched.
    n_strong : int
        Total number of strong MATLAB lines.
    """
    if len(ref_int) == 0 or ref_int.max() == 0:
        return 0, 0
    strong_mask = ref_int / ref_int.max() > int_threshold
    strong_pos = ref_pos[strong_mask]
    n_matched = 0
    for p in strong_pos:
        if len(our_pos) > 0 and np.min(np.abs(our_pos.numpy() - p)) < tol_mhz:
            n_matched += 1
    return n_matched, int(strong_mask.sum())


# ---------------------------------------------------------------------------
# Case 1: S=1/2 + 1H, isotropic A=10 MHz, theta=0
# ---------------------------------------------------------------------------

class TestEndorfrqVsMatlab1H_Axial:
    """Compare endorfrq to MATLAB: 1H isotropic A=10 MHz, field along z."""

    def _load(self):
        path = _require_mat("endorfrq_ref_1H_axial.mat")
        data = loadmat(str(path))
        return data

    def _make_sys(self):
        return SpinSystem(S=[0.5], g=[[2.0, 2.0, 2.0]], Nucs=["1H"], A=[[10.0, 10.0, 10.0]])

    def test_line_count_matches(self):
        data = self._load()
        ref_pos = data["pos1"].ravel()
        ref_int = data["int1"].ravel()
        B_res = float(np.asarray(data["B_res"]).squeeze())
        mwFreq = float(np.asarray(data["mwFreq"]).squeeze())

        sys = self._make_sys()
        freqs, intens, _ = endorfrq(sys, B_res, phi=0.0, theta=0.0,
                                    freq_range=(0.0, 50.0))

        n_matched, n_strong = _match_lines(ref_pos, ref_int, freqs, intens)
        assert n_strong >= 1, "No strong MATLAB lines found"
        assert n_matched == n_strong, (
            f"Only {n_matched}/{n_strong} strong MATLAB lines matched "
            f"(pos={ref_pos}, ours={freqs.numpy()})"
        )

    def test_frequencies_within_1mhz(self):
        data = self._load()
        ref_pos = np.sort(data["pos1"].ravel())
        ref_int = data["int1"].ravel()
        B_res = float(np.asarray(data["B_res"]).squeeze())

        sys = self._make_sys()
        freqs, intens, _ = endorfrq(sys, B_res, phi=0.0, theta=0.0,
                                    freq_range=(0.0, 50.0))

        our_pos = np.sort(freqs.numpy())
        # All strong MATLAB lines within 1 MHz of a torchspin line
        strong_mask = ref_int / ref_int.max() > 0.01
        for p in ref_pos[strong_mask]:
            diffs = np.abs(our_pos - p)
            assert diffs.min() < 1.0, (
                f"MATLAB line at {p:.3f} MHz not matched (closest={diffs.min():.3f} MHz)"
            )


