# ---------------------------------------------------------------------------
# Salt (powder ENDOR) — 1H
# ---------------------------------------------------------------------------

class TestSaltVsMatlab1H:
    """Compare salt powder ENDOR to MATLAB for 1H isotropic A=10 MHz."""

    def _load(self):
        path = _require_mat("salt_ref_1H.mat")
        return loadmat(str(path))

    def test_cosine_similarity(self):
        data = self._load()
        x_ref = data["x_salt1"].ravel()  # MHz
        y_ref = data["y_salt1"].ravel()

        sys = SpinSystem(S=[0.5], g=[[2.0, 2.0, 2.0]], Nucs=["1H"], A=[[10.0, 10.0, 10.0]])
        # Range must bracket the EPR resonance (~338.4 mT) for resfields to find it
        exp_salt = Experiment(mwFreq=9.5, Range=[330.0, 350.0], nPoints=256)

        x_our, y_our = salt(
            sys,
            exp_salt,
            opt=Options(GridSize=31, Verbosity=0),
            freq_range=(float(x_ref.min()), float(x_ref.max())),
            n_points=len(x_ref),
            lw_mhz=0.5,
        )

        x_our_np = x_our.numpy()
        y_our_np = y_our.numpy()

        if y_ref.max() == 0 or y_our_np.max() == 0:
            pytest.skip("One spectrum is all zeros; skipping cosine check")

        cos = _cosine_similarity(y_ref, y_our_np)
        assert cos > 0.92, f"Cosine similarity {cos:.4f} < 0.92"


