# ---------------------------------------------------------------------------
# garlic_hfsign: spectrum invariant under the sign of A
# ---------------------------------------------------------------------------
def test_hyperfine_sign_invariance(cases):
    c = cases['hfsign']
    sys_pos = sys_from_mat(c.Sys)
    exp = exp_from_mat(c.Exp)
    opt = opt_from_mat(c.Opt)
    sys_neg = SpinSystem(S=[0.5], g=sys_pos.g.clone(), Nucs='1H', A=-100.0, lwpp=[0.1, 0.0])
    _, ypos = garlic(sys_pos, exp, opt)
    _, yneg = garlic(sys_neg, exp, opt)
    np.testing.assert_allclose(ypos.numpy(), yneg.numpy(), rtol=1e-3, atol=1e-6 * float(ypos.abs().max()))
    assert cosine(ypos.numpy(), c.y) > 0.9999
    assert cosine(yneg.numpy(), c.yneg) > 0.9999


# ---------------------------------------------------------------------------
# garlic_equivnuclei: n=4 vs four explicit 1H — same integrated spectrum
# ---------------------------------------------------------------------------
def test_equivalent_nuclei_vs_explicit(cases):
    c = cases['equivnuclei']
    exp = exp_from_mat(c.Exp)
    opt = opt_from_mat(c.Opt)
    sys1 = sys_from_mat(c.Sys)
    sys2 = SpinSystem(S=[0.5], Nucs='1H,1H,1H,1H', A=[10, 10, 10, 10], lw=[0, 0.02])
    _, y1 = garlic(sys1, exp, opt)
    _, y2 = garlic(sys2, exp, opt)
    assert abs(y1.sum() / y2.sum() - 1) < 1e-4
    assert cosine(y1.numpy(), c.y) > 0.9999
    assert cosine(y2.numpy(), c.y2) > 0.9999


# ---------------------------------------------------------------------------
# garlic_temperature: Boltzmann polarization scale factor
# ---------------------------------------------------------------------------
def test_temperature_polarization(cases):
    c = cases['temperature']
    sys = sys_from_mat(c.Sys)
    expT = exp_from_mat(c.Exp)
    exp0 = Experiment(mwFreq=expT.mwFreq, Range=expT.Range, nPoints=expT.nPoints, Harmonic=expT.Harmonic)
    _, yT = garlic(sys, expT)
    _, y0 = garlic(sys, exp0)
    ratio_py = float(yT.abs().max() / y0.abs().max())
    ratio_ml = float(np.abs(c.y).max() / np.abs(c.y0).max())
    assert abs(ratio_py / ratio_ml - 1) < 1e-6, (ratio_py, ratio_ml)
    assert cosine(yT.numpy(), c.y) > 0.9999


# ---------------------------------------------------------------------------
# 63Cu, A = 150 MHz: exact vs second-order (second-order shifts are visible)
# ---------------------------------------------------------------------------
def test_cu_exact_and_perturb2(cases):
    c = cases['cu_exact']
    sys = sys_from_mat(c.Sys)
    exp = exp_from_mat(c.Exp)
    _, ye = garlic(sys, exp, Options(Method='exact'))
    _, yp = garlic(sys, exp, Options(Method='perturb2'))
    assert cosine(ye.numpy(), c.y) > 0.9999
    assert cosine(yp.numpy(), c.y_pt2) > 0.9999
    from torchspin.garlic import _resonance_lines, _isotropic_g
    from torchspin.constants import PLANCK, BMAGN
    giso = _isotropic_g(sys)
    central = 9.5e9 * PLANCK / (BMAGN * giso) * 1e3
    pos, _, _, _ = _resonance_lines(sys, giso, central, True, 9.5e9, None, 0, 1e-12, 15, False)
    np.testing.assert_allclose(np.sort(pos), np.sort(np.asarray(c.resfields, dtype=float)), atol=1e-6)


